import { build } from "esbuild";
import { mkdir, copyFile, writeFile } from "node:fs/promises";
import path from "node:path";
const root = path.resolve(import.meta.dirname, "..");
const out = path.join(root, "vendor/ai");
await mkdir(out, { recursive: true });
await build({
  entryPoints: [path.join(root, "src/ai/worker.js")],
  outfile: path.join(out, "worker.js"), bundle: true, format: "esm", platform: "browser",
  target: "chrome116", minify: true, legalComments: "eof",
  external: ["./ort.wasm.min.mjs"],
});
for (const file of ["ort.wasm.min.mjs", "ort-wasm-simd-threaded.mjs", "ort-wasm-simd-threaded.wasm"]) {
  await copyFile(path.join(root, "node_modules/onnxruntime-web/dist", file), path.join(out, file));
}
for (const [pkg, label] of [["@huggingface/tokenizers", "tokenizers"]]) {
  await copyFile(path.join(root, "node_modules", pkg, "LICENSE"), path.join(out, `${label}-LICENSE`));
}
await copyFile(path.join(root, "vendor/qoamo/ONNXRUNTIME-LICENSE"), path.join(out, "onnxruntime-LICENSE"));
await writeFile(path.join(out, "VERSION.txt"), "onnxruntime-web 1.31.1\n@huggingface/tokenizers 0.2.0\nGenerated by npm run build:ai; JS and WASM ship locally.\n");
console.log("Built extension/vendor/ai (local JS/WASM; weights download only when enabled).");
